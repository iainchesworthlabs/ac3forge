def aspx_framing(r, ctx, ch, nts, cfg, b_iframe, prev_stop):
    c = AspxChannel()
    rel_bits = 2 if nts > 8 else 1
    pos = r.pos
    b = r._get(1)
    if b == 0:
        cls, width, code = FIXFIX, 1, 0
    else:
        b = r._get(1)
        if b == 0:
            cls, width, code = FIXVAR, 2, 0b10
        else:
            b = r._get(1)
            cls, width, code = (VARFIX, 3, 0b110) if b == 0 else (VARVAR, 3, 0b111)
    r.record_raw(pos, width, code, 'aspx_int_class')
    c.int_class = cls
    c.rel_left = []
    c.rel_right = []
    c.var_bord_left = None
    c.var_bord_right = None
    c.freq_res = []
    c.tsg_ptr = 0
    if cls == FIXFIX:
        envbits = cfg['aspx_num_env_bits_fixfix'] + 1
        c.num_env = 1 << r.f(envbits, 'tmp_num_env')
        if c.num_env > 4:
            raise SyntaxFail(f'aspx_num_env {c.num_env} exceeds Table 128 for class {cls}')
        if cfg['aspx_freq_res_mode'] == 0:
            c.freq_res = [r.f(1, 'aspx_freq_res')]
    else:
        if cls == FIXVAR:
            c.var_bord_right = r.f(2, 'aspx_var_bord_right')
            n = r.f(rel_bits, 'aspx_num_rel_right')
            c.rel_right = [2 * r.f(rel_bits, 'aspx_rel_bord_right') + 2 for _ in range(n)]
        else:
            if b_iframe:
                c.var_bord_left = r.f(2, 'aspx_var_bord_left')
            n = r.f(rel_bits, 'aspx_num_rel_left')
            c.rel_left = [2 * r.f(rel_bits, 'aspx_rel_bord_left') + 2 for _ in range(n)]
            if cls == VARVAR:
                c.var_bord_right = r.f(2, 'aspx_var_bord_right')
                n = r.f(rel_bits, 'aspx_num_rel_right')
                c.rel_right = [2 * r.f(rel_bits, 'aspx_rel_bord_right') + 2 for _ in range(n)]
        c.num_env = len(c.rel_left) + len(c.rel_right) + 1
        if c.num_env > 5:
            raise SyntaxFail(f'aspx_num_env {c.num_env} exceeds Table 128 for class {cls}')
        ptr_bits = (c.num_env + 2 - 1).bit_length()  # ceil(log2(num_env + 2))
        c.tsg_ptr = r.f(ptr_bits, 'aspx_tsg_ptr') - 1
        if cfg['aspx_freq_res_mode'] == 0:
            c.freq_res = [r.f(1, 'aspx_freq_res') for _ in range(c.num_env)]
    c.num_noise = 2 if c.num_env > 1 else 1
    # Pseudocode 76/77: atsg_sig borders and atsg_freqres (the aspx_ec_data count needs it)
    if cls == FIXFIX:
        if c.num_env not in T.TAB_BORDER[nts]:
            raise SyntaxFail(f'FIXFIX with {c.num_env} envelopes')
        atsg = list(T.TAB_BORDER[nts][c.num_env])
    else:
        atsg = [0] * (c.num_env + 1)
        if cls == FIXVAR:
            atsg[0] = 0
            atsg[c.num_env] = c.var_bord_right + nts
        else:
            atsg[0] = c.var_bord_left if b_iframe else prev_stop - nts
            atsg[c.num_env] = nts if cls == VARFIX else c.var_bord_right + nts
        for t, v in enumerate(c.rel_left):
            atsg[t + 1] = atsg[t] + v
        for t, v in enumerate(c.rel_right):
            atsg[c.num_env - t - 1] = atsg[c.num_env - t] - v
    mode = cfg['aspx_freq_res_mode']

    def freq_res(a, ptr):
        if mode == 0:
            return c.freq_res[a]
        if mode == 1:
            return 0
        if mode == 2:
            high = (a < ptr and nts > 8) or (atsg[a + 1] - atsg[a]) > (nts / 6.0 + 3.25)
            return 1 if high else 0
        return 1

    if cls == FIXFIX:
        fr0 = freq_res(0, 0)
        c.atsg_freqres = [fr0] * c.num_env
    else:
        c.atsg_freqres = [freq_res(a, c.tsg_ptr) for a in range(c.num_env)]
    return c, atsg[c.num_env]


def aspx_delta_dir(r, c):
    c.sig_dir = [r.f(1, 'aspx_sig_delta_dir') for _ in range(c.num_env)]
    c.noise_dir = [r.f(1, 'aspx_noise_delta_dir') for _ in range(c.num_noise)]


def aspx_ec_data(r, data_type, c, qmode, balance, bands):
    n_high, n_low, n_noise = bands
    stereo = 'BALANCE' if balance else 'LEVEL'
    if data_type == 'SIGNAL':
        q = '30' if qmode else '15'
        f0 = CB[f'ASPX_HCB_ENV_{stereo}_{q}_F0']
        df = CB[f'ASPX_HCB_ENV_{stereo}_{q}_DF']
        dt = CB[f'ASPX_HCB_ENV_{stereo}_{q}_DT']
        n_env = c.num_env
        dirs = c.sig_dir
    else:
        f0 = CB[f'ASPX_HCB_NOISE_{stereo}_F0']
        df = CB[f'ASPX_HCB_NOISE_{stereo}_DF']
        dt = CB[f'ASPX_HCB_NOISE_{stereo}_DT']
        n_env = c.num_noise
        dirs = c.noise_dir
    for env in range(n_env):
        if data_type == 'SIGNAL':
            num_sbg = n_high if c.atsg_freqres[env] else n_low
        else:
            num_sbg = n_noise
        if dirs[env] == 0:
            f0.decode(r, 'aspx_hcw')
            for _ in range(1, num_sbg):
                df.decode(r, 'aspx_hcw')
        else:
            for _ in range(num_sbg):
                dt.decode(r, 'aspx_hcw')


def _aspx_prepare(ctx, occ, b_iframe, r):
    cfg = ctx.state.get('aspx_config')
    if cfg is None:
        raise SyntaxFail('A-SPX data before any aspx_config')
    xkey = ('aspx_xover', occ)
    if b_iframe:
        ctx.state[xkey] = r.f(3, 'aspx_xover_subband_offset')
    if xkey not in ctx.state:
        raise SyntaxFail('A-SPX data before any aspx_xover_subband_offset')
    bands = _aspx_bands(cfg, ctx.state[xkey])
    flen = ctx.flb
    nts = (flen // 64) // T.NUM_TS_IN_ATS[flen]
    return cfg, bands, nts


def aspx_data_1ch(r, ctx):
    occ = ctx.next_aspx_occurrence()
    b_iframe = ctx.b_iframe
    cfg, bands, nts = _aspx_prepare(ctx, occ, b_iframe, r)
    skey = ('aspx_prev_stop', occ, 0)
    c, stop = aspx_framing(r, ctx, 0, nts, cfg, b_iframe, ctx.state.get(skey, nts))
    ctx.state[skey] = stop
    c.qmode = cfg['aspx_quant_mode_env']
    if c.int_class == FIXFIX and c.num_env == 1:
        c.qmode = 0
    aspx_delta_dir(r, c)
    # aspx_hfgen_iwc_1ch() (Table 55)
    n_high, _, n_noise = bands
    for _ in range(n_noise):
        r.f(2, 'aspx_tna_mode')
    if r.f(1, 'aspx_ah_present'):
        for _ in range(n_high):
            r.f(1, 'aspx_add_harmonic')
    if r.f(1, 'aspx_fic_present'):
        for _ in range(n_high):
            r.f(1, 'aspx_fic_used_in_sfb')
    if r.f(1, 'aspx_tic_present'):
        for _ in range(nts):
            r.f(1, 'aspx_tic_used_in_slot')
    aspx_ec_data(r, 'SIGNAL', c, c.qmode, 0, bands)
    aspx_ec_data(r, 'NOISE', c, 0, 0, bands)


def aspx_data_2ch(r, ctx):
    occ = ctx.next_aspx_occurrence()
    b_iframe = ctx.b_iframe
    cfg, bands, nts = _aspx_prepare(ctx, occ, b_iframe, r)
    k0 = ('aspx_prev_stop', occ, 0)
    k1 = ('aspx_prev_stop', occ, 1)
    c0, stop0 = aspx_framing(r, ctx, 0, nts, cfg, b_iframe, ctx.state.get(k0, nts))
    ctx.state[k0] = stop0
    c0.qmode = cfg['aspx_quant_mode_env']
    if c0.int_class == FIXFIX and c0.num_env == 1:
        c0.qmode = 0
    q1 = c0.qmode
    balance = r.f(1, 'aspx_balance')
    if balance == 0:
        c1, stop1 = aspx_framing(r, ctx, 1, nts, cfg, b_iframe, ctx.state.get(k1, nts))
        ctx.state[k1] = stop1
        c1.qmode = cfg['aspx_quant_mode_env']
        if c1.int_class == FIXFIX and c1.num_env == 1:
            c1.qmode = 0
    else:
        # aspx_framing(1) is not read: channel 1 takes channel 0's framing
        # (src/ac4dec/ERRATA.md)
        c1 = AspxChannel()
        for slot in ('int_class', 'num_env', 'num_noise', 'freq_res', 'var_bord_left',
                     'var_bord_right', 'rel_left', 'rel_right', 'tsg_ptr', 'atsg_freqres'):
            setattr(c1, slot, getattr(c0, slot))
        c1.qmode = q1
        ctx.state[k1] = stop0
    aspx_delta_dir(r, c0)
    aspx_delta_dir(r, c1)
    # aspx_hfgen_iwc_2ch(aspx_balance) (Table 56)
    n_high, _, n_noise = bands
    for _ in range(n_noise):
        r.f(2, 'aspx_tna_mode')
    if balance == 0:
        for _ in range(n_noise):
            r.f(2, 'aspx_tna_mode')
    if r.f(1, 'aspx_ah_left'):
        for _ in range(n_high):
            r.f(1, 'aspx_add_harmonic')
    if r.f(1, 'aspx_ah_right'):
        for _ in range(n_high):
            r.f(1, 'aspx_add_harmonic')
    if r.f(1, 'aspx_fic_present'):
        if r.f(1, 'aspx_fic_left'):
            for _ in range(n_high):
                r.f(1, 'aspx_fic_used_in_sfb')
        if r.f(1, 'aspx_fic_right'):
            for _ in range(n_high):
                r.f(1, 'aspx_fic_used_in_sfb')
    if r.f(1, 'aspx_tic_present'):
        copy = r.f(1, 'aspx_tic_copy')
        left = right = 0
        if copy == 0:
            left = r.f(1, 'aspx_tic_left')
            right = r.f(1, 'aspx_tic_right')
        if copy or left:
            for _ in range(nts):
                r.f(1, 'aspx_tic_used_in_slot')
        if right:
            for _ in range(nts):
                r.f(1, 'aspx_tic_used_in_slot')
    aspx_ec_data(r, 'SIGNAL', c0, c0.qmode, 0, bands)
    aspx_ec_data(r, 'SIGNAL', c1, c1.qmode, balance, bands)
    aspx_ec_data(r, 'NOISE', c0, 0, 0, bands)
    aspx_ec_data(r, 'NOISE', c1, 0, balance, bands)


