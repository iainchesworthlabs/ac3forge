"""AC-4 substream syntax transcription (the Python reference for src/ac4dec).

Written from ETSI TS 103 190-1 V1.4.1 (Part 1) and ETSI TS 103 190-2 V1.3.1
(Part 2) alone. Part 2 clause 6 amends Part 1 clause 4 (Part 2 tables 48/49);
bitstream_version 2 is what every stream in scope uses. Every syntax element
read from a substream is recorded as (bit_offset, width, value, name) per the
trace contract (docs/verification.md); the TOC is parsed but not recorded.

In scope: ac4_presentation_substream() (Part 2 6.2.2.3), ac4_substream()
(Part 2 6.2.2.2) with audio_data_chan() and the Part 1 channel elements
(single, pair, 3_0, 5_X, 7_X) in every codec mode, and
emdf_payloads_substream() (Part 1 4.2.4.4). Refused (records read before the
refusal are kept): object, A-JOC, OAMD and HSF extension substreams,
immersive_channel_element(), 22_2_channel_element(), the speech spectral
frontend, 96/192 kHz substreams.

Invariants checked (a failure is reported, the substream stops): audio_data
ends inside audio_size (only fill and byte_align left), the tools metadata of
metadata() uses exactly tools_metadata_size bits, drc_frame() in the
presentation substream uses exactly drc_metadata_size bits, and every
substream (after its final byte_align) ends exactly at its substream_size.

Usage:
  python ac4_syntax.py digest <file.ac4> > out.tsv
  python ac4_syntax.py trace <file.ac4> [first_frame last_frame] > out.tsv
Options (before the command): --literal-ims  do not apply the empirical
presentation_version 2 stereo rule (see src/ac4dec/ERRATA.md).
Diagnostics (refusals, invariant failures) go to stderr; the exit status is
1 when any invariant failed.

API: digest_lines(data, stream_name) -> list of the digest file's lines;
walk_stream(data) yields (frame, substream, kind, records).

Standard library only. The TOC comes from ac4_parse.py (same directory), the
tables from ac4_tables.py (generated by
tools/generators/gen_ac4_reference_tables.py).
"""

