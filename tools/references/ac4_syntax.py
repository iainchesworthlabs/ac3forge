def drc_config(r):
    cfg = {'modes': [], 'curve_flag': {}, 'gains_config': {}}
    nr = r.f(3, 'drc_decoder_nr_modes')
    for _ in range(nr + 1):
        mid = r.f(3, 'drc_decoder_mode_id')
        if mid > 3:
            r.f(5, 'drc_output_level_from')
            r.f(5, 'drc_output_level_to')
        if r.f(1, 'drc_repeat_profile_flag'):
            rid = r.f(3, 'drc_repeat_id')
            if rid not in cfg['curve_flag']:
                raise SyntaxFail(f'drc_repeat_id {rid} names a mode not yet configured')
            cfg['curve_flag'][mid] = cfg['curve_flag'][rid]
            if rid in cfg['gains_config']:
                cfg['gains_config'][mid] = cfg['gains_config'][rid]
        else:
            if not r.f(1, 'drc_default_profile_flag'):
                if r.f(1, 'drc_compression_curve_flag'):
                    cfg['curve_flag'][mid] = 1
                    drc_compression_curve(r)
                else:
                    cfg['curve_flag'][mid] = 0
                    cfg['gains_config'][mid] = r.f(2, 'drc_gains_config')
            else:
                cfg['curve_flag'][mid] = 1
        cfg['modes'].append(mid)
    r.f(3, 'drc_eac3_profile')
    return cfg


def _nr_drc_channels(ch_mode):
    """Part 1 Table 168 and Part 2 Table 69. A mode without LFE takes the count
    of its twin with LFE; 3.0, which has no twin, and a presentation with no
    channel mode have none, so channel-dependent gains there are refused (see
    src/ac4dec/ERRATA.md)."""
    if ch_mode in (0, 1):
        return 1
    if 3 <= ch_mode <= 10:
        return 3
    if 11 <= ch_mode <= 15:
        return 4
    raise Refused(f'channel-dependent DRC gains with no nr_drc_channels for ch_mode {ch_mode}')


def drc_frame(r, b_iframe, state, ch_mode, flb):
    if not r.f(1, 'b_drc_present'):
        # An I-frame that carries no drc_frame() clears the configuration a
        # previous one sent, so a later frame that needs one fails as missing
        # its I-frame (src/ac4dec/ERRATA.md, "Dialogue enhancement and DRC
        # configuration across I-frames").
        if b_iframe:
            state.pop('drc_config', None)
        return
    if b_iframe:
        state['drc_config'] = drc_config(r)
    cfg = state.get('drc_config')
    if cfg is None:
        raise SyntaxFail('drc_data before any drc_config')
    curve_present = 0
    for mid in cfg['modes']:
        flag = cfg['curve_flag'].get(mid)
        if flag == 0:
            size = r.f(6, 'drc_gainset_size_value')
            if r.f(1, 'b_more_bits'):
                size += r.vb(2, 'variable_bits') << 6
            version = r.f(2, 'drc_version')
            used = 0
            if version <= 1:
                start = r.pos
                r.f(7, 'drc_gain_val')
                if cfg['gains_config'].get(mid, 0) > 0:
                    n_ch = _nr_drc_channels(ch_mode)
                    n_bands = T.NR_DRC_BANDS[cfg['gains_config'][mid]]
                    n_sf = T.NR_DRC_SUBFRAMES[flb]
                    for ch in range(n_ch):
                        for band in range(n_bands):
                            for sf in range(n_sf):
                                if sf != 0 or band != 0 or ch != 0:
                                    CB['DRC_HCB'].decode(r, 'drc_gain_code')
                used = r.pos - start
            # Version 0 reads nothing by the size, which the text counts both
            # with and without drc_version; any other size is a misread (see
            # src/ac4dec/ERRATA.md).
            if version == 0 and size not in (used, used + 2):
                raise SyntaxFail(f'drc_gainset_size {size} does not match the {used} bits read')
            if version >= 1:
                _wide(r, size - 2 - used, 'drc2_bits')
        elif flag == 1:
            curve_present = 1
    if curve_present:
        r.f(1, 'drc_reset_flag')
        r.f(2, 'drc_reserved')


