_U64 = struct.Struct('>Q').unpack_from
_PACK = struct.Struct('<IHQ').pack
_MASK64 = (1 << 64) - 1


class Reader:
    __slots__ = ('buf', 'end', 'pos', 'recs')

    def __init__(self, data, recs=None):
        self.buf = bytes(data) + b'\0' * 16
        self.pos = 0
        self.end = len(data) * 8
        self.recs = recs

    # -- raw access --------------------------------------------------------
    def peek(self, n):
        """Next n (<= 57) bits without consuming; zero bits past the end."""
        pos = self.pos
        return (_U64(self.buf, pos >> 3)[0] >> (64 - (pos & 7) - n)) & ((1 << n) - 1)

    def _get(self, n):
        pos = self.pos
        npos = pos + n
        if npos > self.end:
            raise SyntaxFail(f'read of {n} bits at bit {pos} runs past the end ({self.end})')
        if n <= 57:
            v = (_U64(self.buf, pos >> 3)[0] >> (64 - (pos & 7) - n)) & ((1 << n) - 1)
        else:
            v = 0
            left = n
            p = pos
            while left:
                k = 57 if left > 57 else left
                v = (v << k) | ((_U64(self.buf, p >> 3)[0] >> (64 - (p & 7) - k)) & ((1 << k) - 1))
                p += k
                left -= k
        self.pos = npos
        return v

    def u(self, n):
        """Unrecorded read (TOC)."""
        if n == 0:
            return 0
        return self._get(n)

    def f(self, n, name):
        """Recorded fixed- or computed-width field."""
        if n == 0:
            return 0
        if n < 0:
            raise SyntaxFail(f'{name}: negative width {n}')
        pos = self.pos
        v = self._get(n)
        self.recs.append((pos, n, v, name))
        return v

    def vb(self, n_bits, name):
        """variable_bits(n_bits) (Part 1 4.2.2) as one record, whose value is
        kept modulo 2^64 as the trace packs it. A record's width is 16 bits, so
        an element wider than 65535 bits is recorded as consecutive 65535-bit
        records, the last shorter, each valued at its own last 64 bits - the
        rule _wide() follows, and the decoder's emit_element() with it."""
        pos = self.pos
        value = 0
        while True:
            value += self._get(n_bits)
            if not self._get(1):
                break
            value <<= n_bits
            value += 1 << n_bits
        width = self.pos - pos
        if width <= 65535:
            self.recs.append((pos, width, value & _MASK64, name))
            return value
        end = self.pos
        at = pos
        while at < end:
            chunk = min(65535, end - at)
            self.pos = at
            self.recs.append((at, chunk, self._get(chunk) & _MASK64, name))
            at += chunk
        self.pos = end
        return value

    def vb_u(self, n_bits):
        value = 0
        while True:
            value += self._get(n_bits)
            if not self._get(1):
                return value
            value <<= n_bits
            value += 1 << n_bits

    def align(self, base=0):
        """byte_align relative to bit position `base` (not recorded)."""
        rem = (self.pos - base) % 8
        if rem:
            npos = self.pos + 8 - rem
            if npos > self.end:
                raise SyntaxFail(f'byte_align at bit {self.pos} runs past the end ({self.end})')
            self.pos = npos

    def record_raw(self, pos, width, value, name):
        self.recs.append((pos, width, value, name))


