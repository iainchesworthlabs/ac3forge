IMS_STEREO_CODE = 0b1111000


def _groups_of(toc, p):
    """The ac4_substream_group_info() dicts a presentation references
    (group_index for bitstream_version 2, inline dicts for version 1), each
    once. A presentation may name one group twice; the group holds the same
    substreams either way, so the helpers of 6.3.3.1.29 to 6.3.3.1.31 count
    them once (src/ac4dec/ERRATA.md, 'A substream group named twice')."""
    groups = toc.get('substream_groups') or []
    out = []
    for ref in p.get('group_refs', []):
        if isinstance(ref, int):
            if ref < len(groups):
                g = groups[ref]
            else:
                continue
        else:
            g = ref
        if not any(g is seen for seen in out):
            out.append(g)
    return out


def presentation_context(toc, p):
    """Part 2 6.3.3.1.13 and 6.3.3.1.27-31 helper variables."""
    pcm = -1
    pcmc = -1
    obj = 0
    adaptive = 0
    b4 = 0
    top_pairs = 0
    n_subs = 0
    for g in _groups_of(toc, p):
        for s in g['substreams']:
            info = s['info']
            n_subs += 1
            if g['b_channel_coded']:
                cm = info['ch_mode']
                if cm is not None:
                    pcm = superset(pcm, cm)
                    core = 5 if cm in (11, 13) else 6 if cm in (12, 14) else -1
                    pcmc = superset(pcmc, core, _CORE_SETS)
                oc = info.get('original_content') or {}
                if oc:
                    b4 = b4 or int(oc['b_4_back_channels_present'])
                    tcp = oc['top_channels_present']
                    top_pairs = max(top_pairs, 2 if tcp == 3 else 1 if tcp in (1, 2) else 0)
            else:
                obj = 1
                if s['kind'] == 'ajoc' and info['b_static_dmx']:
                    pcmc = superset(pcmc, 4 if info['b_lfe'] else 3, _CORE_SETS)
                else:
                    adaptive = 1
    for _, info in p.get('substreams', []):  # presentation_version 0 (Part 1 Table 5)
        n_subs += 1
        if info['ch_mode'] is not None:
            pcm = superset(pcm, info['ch_mode'])
    if obj:
        pcm = -1
    if adaptive:
        pcmc = -1
    if pcmc == pcm:
        pcmc = -1
    has_lfe = int(contains_lfe(pcm)) if pcm >= 0 else int(pcmc in (4, 6))
    ps = p.get('presentation_substream') or {}
    return {'pres_ch_mode': pcm, 'pres_ch_mode_core': pcmc, 'b_pres_4_back_channels_present': b4,
            'pres_top_channel_pairs': top_pairs, 'b_pres_has_lfe': has_lfe,
            'n_substreams_in_presentation': n_subs,
            'n_substream_groups': p.get('n_substream_groups', 1),
            'b_alternative': ps.get('b_alternative', 0), 'b_pres_ndot': ps.get('b_pres_ndot', 0)}


def substream_roles(toc):
    """substream index -> (kind, details); the first referencing info element
    in TOC order decides (Part 1 Table 15, Part 2 Table 50)."""
    roles = {}

    def put(idx, role):
        if idx is not None and idx not in roles:
            roles[idx] = role

    def audio(info, sus_ver, kind, owner, frames_key):
        idx = info.get('substream_index')
        if idx is None:
            return
        # 4.3.3.7.9: with a frame rate factor above 1 the element names a
        # series of consecutive substreams. They are consecutive codec frames
        # of one signal (4.3.3.5.3), and b_iframe_global answers to the first
        # of them (4.3.3.2.7), so they share the first instance's carried
        # state and each covers frame_len_base / factor samples.
        frames = info.get(frames_key) or [0]
        for i, ndot in enumerate(frames):
            put(idx + i, ('audio', {'info': info, 'sus_ver': sus_ver, 'kind': kind,
                                    'b_iframe': ndot, 'owner': owner,
                                    'state_key': idx, 'frame_rate_factor': len(frames)}))

    pres = toc['presentations']
    for p in pres:
        for e in [p.get('emdf'), *(p.get('emdf_substreams') or [])]:
            if e:
                put(e.get('payloads_substream_index'), ('emdf_payloads', p))
        ps = p.get('presentation_substream')
        if ps:
            put(ps['substream_index'], ('presentation', p))
        for _, info in p.get('substreams', []):
            audio(info, 0, 'chan', p, 'b_iframe')
            put(info.get('hsf_ext_substream_index'), ('hsf_ext', p))
    seen = []
    for p in pres:
        for g in _groups_of(toc, p):
            if any(g is x for x in seen):
                continue
            seen.append(g)
            if g.get('oamd') and g['oamd'].get('substream_index') is not None:
                put(g['oamd']['substream_index'], ('oamd', g))
            for s in g['substreams']:
                audio(s['info'], s['sus_ver'], s['kind'], p, 'b_audio_ndot')
                put(s.get('hsf_ext_substream_index'), ('hsf_ext', g))
    return roles


def apply_ims_rule(toc):
    """The observed rule (src/ac4dec/ERRATA.md): in a presentation_version 2 presentation,
    channel_mode 0b1111000 is read as stereo (ch_mode 1)."""
    for p in toc['presentations']:
        if p.get('presentation_version') != 2:
            continue
        for g in _groups_of(toc, p):
            if g['b_channel_coded']:
                for s in g['substreams']:
                    if s['info']['channel_mode'] == IMS_STEREO_CODE:
                        s['info']['ch_mode'] = 1


def _derive_assoc_dialog(p, info):
    """Part 1 4.3.12.4.1 / 4.3.12.4.2 for sus_ver 0 (src/ac4dec/ERRATA.md)."""
    cfg = p.get('presentation_config')
    subs = [x for _, x in p.get('substreams', [])]
    pos = next((i for i, x in enumerate(subs) if x is info), -1)
    cc = (info.get('content_type') or {}).get('content_classifier')
    assoc = 1 if cc in (0b101, 0b011, 0b010) else 0
    if (cfg == 2 and pos == 1) or (cfg in (3, 4) and pos == 2):
        assoc = 1
    dialog = 1 if (cfg in (0, 3) and pos == 1) or cc == 0b100 else 0
    return assoc, dialog


class StreamWalker:
    """Walks sync frames; configuration sent in I-frames persists per
    (kind, substream index) across frames."""

    def __init__(self, ims_rule=True):
        self.ims_rule = ims_rule
        self.state = {}
        self.previous_counter = None

    def frame(self, raw):
        """Returns [(index, kind, recs, error_or_None)] for one raw_ac4_frame()."""
        r = ac4_parse.Reader(raw)
        toc = ac4_parse.parse_ac4_toc(r)
        # Part 1 4.3.3.2.2: the stream continues when sequence_counter is the
        # previous value plus 1, wraps from 1020 to 1, or follows a 0; anything
        # else is a change of source, after which nothing carried is used.
        counter, previous = toc['sequence_counter'], self.previous_counter
        if previous is not None and not (counter == previous + 1
                                         or (counter == 1 and previous == 1020)
                                         or (counter != 0 and previous == 0)):
            self.state.clear()
        if self.ims_rule:
            apply_ims_rule(toc)
        # Tables 83 and 84: index 13 is the only frame rate Table 84 defines at
        # 44.1 kHz, so every other index there has no frame length, the way the
        # decoder's frame_len_base() reads the pair.
        if toc['fs_index'] == 0 and toc['frame_rate_index'] != 13:
            flb = None
        else:
            flb = T.FRAME_LEN_BASE.get(toc['frame_rate_index'])
        # Part 2 5.1.3: with frame_rate_fraction above 1 a coded frame is spread
        # over 2 or 4 transmission frames, so this frame holds fragments rather
        # than whole substreams. Assembling them is out of scope, and reading a
        # fragment as a substream would report a legal stream as a damaged one,
        # so every substream of such a frame is refused, as the decoder does.
        fragmented = any(p.get('frame_rate_fraction', 1) != 1 for p in toc['presentations'])
        roles = substream_roles(toc)
        out = []
        offset = toc['toc_bytes'] + toc['payload_base']
        sizes = toc['substream_sizes'] if toc['b_size_present'] else [max(0, len(raw) - offset)]
        # Substreams that run past the frame make the frame's table of
        # contents wrong, so none of them is read.
        end = offset
        for size in sizes:
            end += size
            if end > len(raw):
                raise ValueError(
                    f'substreams run past the end of the frame ({end} > {len(raw)} bytes)')
        # Only a frame that parses this far counts as the predecessor of the
        # next one: the decoder takes its counter from ac4::parse_raw_frame(),
        # which reports no table of contents at all when the substreams overrun,
        # so a frame rejected here leaves the counter where it was and the next
        # frame reads as a change of source (src/ac4dec/ERRATA.md, "A change of
        # source").
        self.previous_counter = counter
        for idx, size in enumerate(sizes):
            data = raw[offset:offset + size]
            offset += size
            role = roles.get(idx)
            kind = role[0] if role else 'unreferenced'
            recs = []
            err = None
            try:
                if len(data) != size:
                    raise SyntaxFail(f'substream {idx} ({size} bytes) runs past the end of '
                                     'the frame')
                if fragmented:
                    raise Refused('a frame of the efficient high frame rate mode, whose '
                                  'substreams are fragments')
                if kind == 'presentation':
                    # The same reserved-frame-rate check the audio branch
                    # makes below: without it a frame length of None reaches
                    # the DRC subframe table as a key, and the KeyError is
                    # caught by neither handler - it ends the whole walk
                    # instead of this one substream. The decoder refuses it
                    # per substream (nr_drc_subframes of a frame length
                    # Table 169 does not list).
                    if flb is None:
                        raise SyntaxFail(f'frame_rate_index {toc["frame_rate_index"]} is reserved')
                    pc = presentation_context(toc, role[1])
                    st = self.state.setdefault(('presentation', idx), {})
                    parse_presentation_substream(data, pc, flb, st, recs)
                elif kind == 'emdf_payloads':
                    parse_emdf_payloads(data, recs)
                elif kind == 'audio':
                    a = role[1]
                    info = a['info']
                    if a['kind'] != 'chan':
                        raise Refused(f'{a["kind"]} substream (object audio)')
                    if info['ch_mode'] is None:
                        raise Refused(f'reserved channel_mode {info["channel_mode"]:#b}')
                    if flb is None:
                        raise SyntaxFail(f'frame_rate_index {toc["frame_rate_index"]} is reserved')
                    owner = a['owner']
                    ps = owner.get('presentation_substream') if owner else None
                    b_alt = ps['b_alternative'] if ps else 0
                    b_assoc = b_dlg = 0
                    if a['sus_ver'] == 0 and owner is not None:
                        b_assoc, b_dlg = _derive_assoc_dialog(owner, info)
                    # The slot is the series' first index, this substream's own
                    # outside a frame-rate-multiplied series; every instance of
                    # a series carries one state, and each covers its share of
                    # the base frame (substream_roles()'s own comment).
                    st = self.state.setdefault(('audio', a['state_key']), {})
                    # What a substream carries between frames belongs to its
                    # channel mode and substream version; a change of either
                    # starts it afresh.
                    if st.get('carried_for') != (info['ch_mode'], a['sus_ver']):
                        st.clear()
                        st['carried_for'] = (info['ch_mode'], a['sus_ver'])
                    factor = a['frame_rate_factor']
                    if factor <= 0 or flb % factor:
                        raise SyntaxFail(f'frame_rate_factor {factor} does not divide '
                                         f'frame_len_base {flb}')
                    parse_ac4_substream(data, info, a['b_iframe'], flb // factor, st, recs, b_alt,
                                        a['sus_ver'], b_assoc, b_dlg)
                elif kind in ('hsf_ext', 'oamd'):
                    raise Refused(f'{kind} substream')
            except Refused as exc:
                err = f'refused: {exc}'
            except SyntaxFail as exc:
                err = f'FAIL: {exc}'
            out.append((idx, 'audio' if kind in ('audio', 'hsf_ext', 'oamd') else kind, recs, err))
        return out


def walk_stream(data, ims_rule=True, diagnostics=None):
    """Yields (frame, substream, kind, records) for every substream with at
    least one record, in frame and substream order. Refusals, invariant
    failures and TOC errors are appended to `diagnostics` (a list) if given."""
    walker = StreamWalker(ims_rule)
    frames = ac4_parse.iter_sync_frames(data)
    fi = -1
    while True:
        try:
            _, _, raw, crc_ok = next(frames)
        except StopIteration:
            return
        except (ValueError, IndexError) as exc:
            if diagnostics is not None:
                diagnostics.append(f'sync after frame {fi}: FAIL: {exc}')
            return
        fi += 1
        if crc_ok is False and diagnostics is not None:
            diagnostics.append(f'frame {fi}: FAIL: CRC mismatch')
        try:
            subs = walker.frame(raw)
        except (ValueError, IndexError) as exc:
            if diagnostics is not None:
                diagnostics.append(f'frame {fi}: TOC: FAIL: {exc}')
            continue
        for idx, kind, recs, err in subs:
            if err and diagnostics is not None:
                diagnostics.append(f'frame {fi} substream {idx} ({kind}): {err}')
            if recs:
                yield fi, idx, kind, recs


def digest_line(frame, idx, kind, recs):
    crc = 0
    pack = _PACK
    buf = bytearray()
    for pos, width, value, _ in recs:
        buf += pack(pos, width, value)
        if len(buf) > 65536:
            crc = zlib.crc32(buf, crc)
            buf.clear()
    crc = zlib.crc32(buf, crc)
    last = recs[-1]
    return f'{frame}\t{idx}\t{kind}\t{len(recs)}\t{last[0] + last[1]}\t0x{crc:08x}'


DIGEST_COLUMNS = '# frame\tsubstream\tkind\trecords\tend_bit\tcrc32'


def digest_lines(data: bytes, stream_name: str, ims_rule=True, diagnostics=None) -> list[str]:
    """The digest file's lines (trace contract, 'Digests'), without newlines."""
    lines = [f'# ac4-syntax-digest/1 {stream_name}', DIGEST_COLUMNS]
    for fi, idx, kind, recs in walk_stream(data, ims_rule, diagnostics):
        lines.append(digest_line(fi, idx, kind, recs))
    return lines


def stream_label(path):
    """Path relative to tests/golden/external-baseline/ when inside it, else the file name."""
    p = Path(path).resolve().as_posix()
    marker = '/tests/golden/external-baseline/'
    if marker in p:
        return p.split(marker, 1)[1]
    return Path(path).name


def run(argv):
    ims_rule = True
    args = list(argv)
    if args and args[0] == '--literal-ims':
        ims_rule = False
        args = args[1:]
    if len(args) < 2 or args[0] not in ('digest', 'trace'):
        sys.stderr.write(__doc__)
        return 2
    cmd, path = args[0], args[1]
    data = Path(path).read_bytes()
    label = stream_label(path)
    diagnostics = []
    out = sys.stdout
    if cmd == 'digest':
        for line in digest_lines(data, label, ims_rule, diagnostics):
            out.write(line + '\n')
    else:
        first, last = 0, None
        if len(args) >= 4:
            first, last = int(args[2]), int(args[3])
        for fi, idx, _kind, recs in walk_stream(data, ims_rule, diagnostics):
            if last is not None and fi > last:
                break
            if fi >= first:
                out.write(''.join(f'{fi}\t{idx}\t{p}\t{w}\t{v}\t{n}\n' for p, w, v, n in recs))
    fails = [d for d in diagnostics if 'FAIL' in d]
    for d in diagnostics:
        sys.stderr.write(d + '\n')
    sys.stderr.write(f'{label}: {len(fails)} failures, {len(diagnostics) - len(fails)} refusals\n')
    return 1 if fails else 0


if __name__ == '__main__':
    sys.exit(run(sys.argv[1:]))
