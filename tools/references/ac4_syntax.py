def _tracks_at(ctx, mark, positions):
    """The sf_info of the channel data's tracks at `positions` (counted from
    the first sf_data() read after `mark`)."""
    out = []
    for p in positions:
        if mark + p >= len(ctx.tracks):
            raise SyntaxFail('the channel data holds fewer tracks than its mapping names')
        out.append(ctx.tracks[mark + p])
    return out


def _residual_sfis(r, bases):
    """max_sfb_master and the sf_info of the two residuals after it (Part 1
    4.3.5.13, notes to Tables 25 and 33; see src/ac4dec/ERRATA.md). Residual
    i has the framing of the track its A-CPL module pairs it with, bases[i];
    max_sfb_master is n_side_bits of the largest transform length the two
    base sf_info() signal; a window group of that length takes it as its
    max_sfb, a shorter one Tables B.8 to B.19's value."""
    largest = max(s.largest_len() for s in bases)
    master = r.f(T.N_MSFB_BITS_48[largest][1], 'max_sfb_master')
    residuals = []
    for base in bases:
        m = SfInfo()
        for slot in ('flb', 'long_frame', 'tl', 'tl_len', 'max_sfb', 'max_sfb_side',
                     'b_dual_maxsfb', 'b_side_limited', 'num_windows', 'num_window_groups',
                     'window_to_group', 'num_win_in_group', 'group_tl', 'group_len', 'group_idx'):
            setattr(m, slot, getattr(base, slot))
        override = []
        for g in range(base.num_window_groups):
            length = base.group_len[g]
            if length == largest:
                override.append(master)
            else:
                override.append(T.N_SFB_SIDE[largest][length][master])
        m.master_override = override
        residuals.append(m)
    return residuals


