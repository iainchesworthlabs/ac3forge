def _aspx_bands(cfg, xover):
    """Pseudocode 67-70: num_sbg_sig_highres, num_sbg_sig_lowres, num_sbg_noise."""
    start, stop = cfg['aspx_start_freq'], cfg['aspx_stop_freq']
    if cfg['aspx_master_freq_scale'] == 1:
        n_master = 22 - 2 * start - 2 * stop
        tmpl = T.SBG_TEMPLATE_HIGHRES
    else:
        n_master = 20 - 2 * start - 2 * stop
        tmpl = T.SBG_TEMPLATE_LOWRES
    if n_master < 1:
        raise SyntaxFail(f'num_sbg_master {n_master}')
    master = tmpl[2 * start:2 * start + n_master + 1]
    sbz = master[n_master]
    n_high = n_master - xover
    if n_high < 1:
        raise SyntaxFail(f'aspx_xover_subband_offset {xover} >= num_sbg_master {n_master}')
    sbx = master[xover]
    n_low = n_high - n_high // 2
    n_noise = max(1, math.floor(cfg['aspx_noise_sbg'] * math.log2(sbz / sbx) + 0.5))
    # 5.7.6.3.1.3 caps num_sbg_noise at 5. Five of the 1,808 legal A-SPX
    # settings give more, all with aspx_noise_sbg 3 on the low-resolution
    # master scale, and reading on there would take a noise envelope per band
    # the syntax does not have (src/ac4dec/ERRATA.md, "num_sbg_noise above 5").
    if n_noise > 5:
        raise SyntaxFail(f'num_sbg_noise {n_noise} exceeds 5 (5.7.6.3.1.3)')
    return n_high, n_low, n_noise


