class Codebook:
    __slots__ = (
        'cb_mod',
        'cb_mod2',
        'cb_mod3',
        'cb_off',
        'l1',
        'long',
        'maxlen',
        'name',
        'shift',
        'size',
        'table',
    )

    def __init__(self, name, spec):
        lens, cws = spec['len'], [int(c, 16) if isinstance(c, str) else c for c in spec['cw']]
        self.name = name
        self.size = len(lens)
        self.maxlen = max(lens)
        self.l1 = min(self.maxlen, 10)
        self.shift = self.maxlen - self.l1
        self.table = [None] * (1 << self.l1)
        self.long = {}
        for i, (length, cw) in enumerate(zip(lens, cws, strict=True)):
            if length <= self.l1:
                base = cw << (self.l1 - length)
                for k in range(1 << (self.l1 - length)):
                    if self.table[base + k] is not None:
                        raise ValueError(f'{name}: codebook not prefix-free')
                    self.table[base + k] = (length, i)
            else:
                self.long[(length, cw)] = i
        self.cb_off = spec['cb_off']
        self.cb_mod = spec['cb_mod']
        self.cb_mod2 = spec['cb_mod2']
        self.cb_mod3 = spec['cb_mod3']

    def decode(self, r, name):
        """huff_decode(): record (length, index) and return the index."""
        pos = r.pos
        maxlen = self.maxlen
        bits = (_U64(r.buf, pos >> 3)[0] >> (64 - (pos & 7) - maxlen)) & ((1 << maxlen) - 1)
        e = self.table[bits >> self.shift]
        if e is not None:
            length, idx = e
        else:
            for length in range(self.l1 + 1, maxlen + 1):
                idx = self.long.get((length, bits >> (maxlen - length)))
                if idx is not None:
                    break
            else:
                raise SyntaxFail(f'{self.name}: no codeword at bit {pos}')
        npos = pos + length
        if npos > r.end:
            raise SyntaxFail(f'{self.name} codeword at bit {pos} runs past the end ({r.end})')
        r.pos = npos
        r.recs.append((pos, length, idx, name))
        return idx


