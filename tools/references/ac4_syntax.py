def _wide(r, n, name):
    """A field the stream sizes and the syntax does not interpret (add_data,
    extensions_bits, drc2_bits): one record of its width, valued at its last
    64 bits. A record's width is 16 bits, so a field longer than 65535 bits is
    recorded as consecutive 65535-bit records, the last shorter."""
    if n < 0:
        raise SyntaxFail(f'{name}: negative width {n}')
    while n > 0:
        width = min(n, 65535)
        pos = r.pos
        v = r._get(width)
        r.recs.append((pos, width, v & _MASK64, name))
        n -= width


