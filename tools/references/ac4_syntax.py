def chparam_info(r, sfi):
    sap_mode = r.f(2, 'sap_mode')
    if sap_mode == 1:
        for g in range(sfi.num_window_groups):
            for _ in range(sfi.get_max_sfb(g)):
                r.f(1, 'ms_used')
    elif sap_mode == 3:
        # sap_data() (Table 48)
        ngroups = sfi.num_window_groups
        used = []
        if r.f(1, 'sap_coeff_all') == 0:
            for g in range(ngroups):
                m = sfi.get_max_sfb(g)
                u = [0] * m
                for sfb in range(0, m, 2):
                    u[sfb] = r.f(1, 'sap_coeff_used')
                    if sfb + 1 < m:
                        u[sfb + 1] = u[sfb]
                used.append(u)
        else:
            used = [[1] * sfi.get_max_sfb(g) for g in range(ngroups)]
        if ngroups != 1:
            r.f(1, 'delta_code_time')
        for g in range(ngroups):
            m = sfi.get_max_sfb(g)
            for sfb in range(0, m, 2):
                if used[g][sfb]:
                    CB_SCALEFAC.decode(r, 'sap_hcw')


def companding_control(r, num_chan):
    sync = r.f(1, 'sync_flag') if num_chan > 1 else 0
    need_avg = 0
    for _ in range(1 if sync else num_chan):
        if not r.f(1, 'b_compand_on'):
            need_avg = 1
    if need_avg:
        r.f(1, 'b_compand_avg')


