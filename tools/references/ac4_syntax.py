class SfInfo:
    """asf_transform_info() + asf_psy_info() and the helper elements of
    Part 1 4.3.6.2.6 (Pseudocode 3/4) and get_max_sfb / get_transf_length."""

    __slots__ = (
        'b_dual_maxsfb',
        'b_side_limited',
        'flb',
        'group_idx',
        'group_len',
        'group_tl',
        'long_frame',
        'master_override',
        'max_sfb',
        'max_sfb_side',
        'num_win_in_group',
        'num_window_groups',
        'num_windows',
        'tl',
        'tl_len',
        'window_to_group',
    )

    def get_max_sfb(self, g, side=False):
        if self.master_override is not None:
            return self.master_override[g]
        idx = self.group_idx[g]
        if self.b_side_limited or (self.b_dual_maxsfb and side):
            return self.max_sfb_side[idx]
        return self.max_sfb[idx]

    def largest_len(self):
        return max(self.tl_len)


def _full_frame_index(flb):
    """The transform index whose transform covers the whole frame (Table 103):
    4 at 1536 samples and above, 3 for 1024, 960 and 768, 2 for 512 and 384.
    It decides the widths Table 39 takes from the index, not only the length."""
    if flb >= 1536:
        return 4
    return 2 if flb in (512, 384) else 3


def sf_info_lfe(r, ctx):
    """Part 1 Table 35."""
    flb = ctx.flb
    s = SfInfo()
    s.flb = flb
    s.long_frame = 1
    # Table 35 gives the LFE no transf_length: its transform covers the frame,
    # so the index is the whole-frame one. This used to be 4 whatever the frame
    # length, which reads sect_len_incr 5 bits wide at 512 and 384 samples where
    # Table 39 takes 3 (src/ac4dec/ERRATA.md, "sf_info_lfe() below 1536 samples"
    # and "n_sect_bits below 1536 samples").
    s.tl = (_full_frame_index(flb),) * 2
    s.tl_len = (flb, flb)
    bits = T.N_MSFB_BITS_48[flb][2]
    s.max_sfb = [r.f(bits, 'max_sfb[0]'), 0]
    s.max_sfb_side = [0, 0]
    s.b_dual_maxsfb = 0
    s.b_side_limited = 0
    s.num_windows = 1
    s.num_window_groups = 1
    s.window_to_group = [0]
    s.num_win_in_group = [1]
    s.group_tl = [s.tl[0]]
    s.group_len = [flb]
    s.group_idx = [0]
    s.master_override = None
    if s.max_sfb[0] > T.NUM_SFB_48[flb]:
        raise SyntaxFail(f'LFE max_sfb {s.max_sfb[0]} > num_sfb {T.NUM_SFB_48[flb]}')
    return s


def sf_info(r, ctx, b_dual_maxsfb=0, b_side_limited=0):
    """Part 1 Table 34 for spec_frontend == ASF (Tables 37, 38)."""
    flb = ctx.flb
    s = SfInfo()
    s.flb = flb
    s.b_dual_maxsfb = b_dual_maxsfb
    s.b_side_limited = b_side_limited
    s.master_override = None
    # asf_transform_info()
    if flb >= 1536:
        s.long_frame = r.f(1, 'b_long_frame')
        if s.long_frame == 0:
            t0 = r.f(2, 'transf_length[0]')
            t1 = r.f(2, 'transf_length[1]')
            s.tl = (t0, t1)
            row = T.TRANSF_LENGTH_LONG_BASE[flb]
            s.tl_len = (row[t0], row[t1])
            n_grp_bits = T.N_GRP_BITS_LONG_BASE[(t0, t1)]
        else:
            s.tl = (4, 4)
            s.tl_len = (flb, flb)
            n_grp_bits = 0
    else:
        s.long_frame = 0
        t = r.f(2, 'transf_length')
        length = T.TRANSF_LENGTH_SHORT_BASE[flb][t]
        if length is None:
            raise SyntaxFail(f'transf_length {t} not allowed for frame_len_base {flb}')
        s.tl = (t, t)
        s.tl_len = (length, length)
        n_grp_bits = T.N_GRP_BITS_SHORT_BASE[flb][t]
    # asf_psy_info()
    b_diff = 1 if (flb >= 1536 and s.long_frame == 0 and s.tl[0] != s.tl[1]) else 0
    s.max_sfb = [0, 0]
    s.max_sfb_side = [0, 0]
    for i in ((0, 1) if b_diff else (0,)):
        msfb_bits, side_bits, _ = T.N_MSFB_BITS_48[s.tl_len[i]]
        if b_side_limited:
            s.max_sfb_side[i] = r.f(side_bits, f'max_sfb_side[{i}]')
        else:
            s.max_sfb[i] = r.f(msfb_bits, f'max_sfb[{i}]')
            if b_dual_maxsfb:
                s.max_sfb_side[i] = r.f(msfb_bits, f'max_sfb_side[{i}]')
        n = T.NUM_SFB_48[s.tl_len[i]]
        if s.max_sfb[i] > n or s.max_sfb_side[i] > n:
            raise SyntaxFail(f'max_sfb {s.max_sfb[i]}/{s.max_sfb_side[i]} > num_sfb {n}')
    grouping = [r.f(1, 'scale_factor_grouping_bit') for _ in range(n_grp_bits)] + [0]
    # Pseudocode 3
    num_windows = 1
    num_window_groups = 1
    if s.long_frame == 0:
        num_windows = n_grp_bits + 1
        if b_diff:
            nw0 = 1 << (3 - s.tl[0])
            for i in range(n_grp_bits, nw0 - 1, -1):
                grouping[i] = grouping[i - 1]
            grouping[nw0 - 1] = 0
            num_windows += 1
        window_to_group = [0] * num_windows
        for i in range(num_windows - 1):
            if grouping[i] == 0:
                num_window_groups += 1
            window_to_group[i + 1] = num_window_groups - 1
    else:
        window_to_group = [0]
    s.num_windows = num_windows
    s.num_window_groups = num_window_groups
    s.window_to_group = window_to_group
    s.num_win_in_group = [window_to_group.count(g) for g in range(num_window_groups)]
    # get_transf_length(g) (Pseudocode 2) and the max_sfb index of get_max_sfb(g) (Pseudocode 5)
    s.group_tl = []
    s.group_len = []
    s.group_idx = []
    for g in range(num_window_groups):
        if flb >= 1536:
            if s.long_frame == 0:
                nw0 = 1 << (3 - s.tl[0])
                first_second = window_to_group[nw0]
                k = 0 if g < first_second else 1
                s.group_tl.append(s.tl[k])
                s.group_len.append(s.tl_len[k])
                s.group_idx.append(1 if (b_diff and g >= first_second) else 0)
            else:
                s.group_tl.append(4)
                s.group_len.append(flb)
                s.group_idx.append(0)
        else:
            s.group_tl.append(s.tl[0])
            s.group_len.append(s.tl_len[0])
            s.group_idx.append(0)
    return s


def _group_offsets(sfi, g, max_sfb, group_offset):
    """sect_sfb_offset[g][0..max_sfb] (Pseudocode 4, extended to sfb == max_sfb)."""
    off = T.SFB_OFFSET_48[sfi.group_len[g]]
    nw = sfi.num_win_in_group[g]
    return [group_offset + off[sfb] * nw for sfb in range(max_sfb + 1)]


def sf_data(r, ctx, sfi, side=False):
    """Part 1 Table 36 for ASF: section, spectral, scale factor, SNF data."""
    ngroups = sfi.num_window_groups
    max_sfbs = [sfi.get_max_sfb(g, side) for g in range(ngroups)]
    offsets = []
    group_offset = 0
    for g in range(ngroups):
        bounds = _group_offsets(sfi, g, max_sfbs[g], group_offset)
        offsets.append(bounds)
        group_offset = bounds[-1]
    # asf_section_data() (Table 39)
    sections = []      # per group: list of (cb, sect_start, sect_end)
    sec_lsf = []
    sfb_cbs = []
    for g in range(ngroups):
        tlg = sfi.group_tl[g]
        if tlg <= 2:
            esc, nbits = 7, 3
        else:
            esc, nbits = 31, 5
        n48 = T.NUM_SFB_48[sfi.group_len[g]]
        max_sfb = max_sfbs[g]
        secs = []
        sfb_cb = [0] * max_sfb
        num_sec_lsf = 0
        k = 0
        while k < max_sfb:
            cb = r.f(4, 'sect_cb')
            sect_len = 1
            while True:
                incr = r.f(nbits, 'sect_len_incr')
                if incr != esc:
                    break
                sect_len += esc
            sect_len += incr
            start, end = k, k + sect_len
            if cb > 11:
                raise SyntaxFail(f'sect_cb {cb} is not a Huffman codebook')
            if end > max_sfb:
                raise SyntaxFail(f'section ends at sfb {end} beyond max_sfb {max_sfb}')
            if start < n48 <= end:
                num_sec_lsf = len(secs) + 1
                if end > n48:
                    secs.append((cb, start, n48))
                    secs.append((cb, n48, end))
                else:
                    secs.append((cb, start, end))
            else:
                secs.append((cb, start, end))
            for sfb in range(k, k + sect_len):
                sfb_cb[sfb] = cb
            k += sect_len
        if num_sec_lsf == 0:
            num_sec_lsf = len(secs)
        sections.append(secs)
        sec_lsf.append(num_sec_lsf)
        sfb_cbs.append(sfb_cb)
    # asf_spectral_data() (Table 40)
    max_quant = []
    for g in range(ngroups):
        bounds = offsets[g]
        mq = [0] * max_sfbs[g]
        for i in range(sec_lsf[g]):
            cb, sstart, send = sections[g][i]
            if cb == 0 or cb > 11:
                if cb > 11:
                    raise SyntaxFail(f'sect_cb {cb} is not a Huffman codebook')
                continue
            hcb = ASF_CB[cb]
            dim = T.CB_DIM[cb]
            unsigned = T.UNSIGNED_CB[cb]
            off = hcb.cb_off
            k = bounds[sstart]
            kend = bounds[send]
            s = sstart
            decode = hcb.decode
            while k < kend:
                while k >= bounds[s + 1]:
                    s += 1
                idx = decode(r, 'asf_qspec_hcw')
                if dim == 4:
                    m3, m2, m1 = hcb.cb_mod3, hcb.cb_mod2, hcb.cb_mod
                    q1 = idx // m3 - off
                    idx -= (q1 + off) * m3
                    q2 = idx // m2 - off
                    idx -= (q2 + off) * m2
                    q3 = idx // m1 - off
                    idx -= (q3 + off) * m1
                    q4 = idx - off
                    if unsigned:
                        nz = (q1 != 0) + (q2 != 0) + (q3 != 0) + (q4 != 0)
                        if nz:
                            r.f(nz, 'quad_sign_bits')
                    if q1 or q2 or q3 or q4:
                        mq[s] = 1
                    k += 4
                else:
                    m1 = hcb.cb_mod
                    q1 = idx // m1 - off
                    q2 = idx - (q1 + off) * m1 - off
                    if unsigned:
                        nz = (q1 != 0) + (q2 != 0)
                        if nz:
                            r.f(nz, 'pair_sign_bits')
                    if cb == 11:
                        if q1 == 16:
                            ext_code(r)
                        if q2 == 16:
                            ext_code(r)
                    if q1 or q2:
                        mq[s] = 1
                    k += 2
            if k != kend:
                raise SyntaxFail('spectral codewords overrun the section end')
        max_quant.append(mq)
    # asf_scalefac_data() (Table 41)
    r.f(8, 'reference_scale_factor')
    first = 0
    for g in range(ngroups):
        lim = min(max_sfbs[g], T.NUM_SFB_48[sfi.group_len[g]])
        cbs = sfb_cbs[g]
        mq = max_quant[g]
        for sfb in range(lim):
            if cbs[sfb] != 0 and mq[sfb]:
                if first:
                    CB_SCALEFAC.decode(r, 'asf_sf_hcw')
                else:
                    first = 1
    # asf_snf_data() (Table 42)
    if r.f(1, 'b_snf_data_exists'):
        for g in range(ngroups):
            lim = min(max_sfbs[g], T.NUM_SFB_48[sfi.group_len[g]])
            cbs = sfb_cbs[g]
            mq = max_quant[g]
            for sfb in range(lim):
                if cbs[sfb] == 0 or not mq[sfb]:
                    CB_SNF.decode(r, 'asf_snf_hcw')
    ctx.tracks.append(sfi)


def ext_code(r):
    """Pseudocode 20: one record for the whole escape, value 2^(N_ext+4) + ext_val.
    Table 40 gives ext_code 5 to 21 bits (2 * N_ext + 5), so a ninth leading
    one fails the substream, with nothing recorded (see src/ac4dec/ERRATA.md)."""
    pos = r.pos
    n_ext = 0
    while r._get(1):
        n_ext += 1
        if n_ext > 8:
            raise SyntaxFail('ext_code is longer than 21 bits')
    val = r._get(n_ext + 4)
    r.recs.append((pos, r.pos - pos, (1 << (n_ext + 4)) + val, 'ext_code'))


