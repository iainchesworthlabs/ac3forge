# Channels per ch_mode for superset() (Part 2 6.3.3.1.27): Table 56 plus the
# 7.X.4 / 9.X.4 / 22.2 channel sets of Part 2 table 69.
_CH_SETS = {
    0: {'C'}, 1: {'L', 'R'}, 2: {'L', 'R', 'C'}, 3: {'L', 'R', 'C', 'Ls', 'Rs'},
    5: {'L', 'R', 'C', 'Ls', 'Rs', 'Lb', 'Rb'},
    7: {'L', 'R', 'C', 'Lw', 'Rw', 'Ls', 'Rs'},
    9: {'L', 'R', 'C', 'Ls', 'Rs', 'Tfl', 'Tfr'},
    11: {'L', 'R', 'C', 'Ls', 'Rs', 'Lb', 'Rb', 'Tfl', 'Tfr', 'Tbl', 'Tbr'},
    13: {'L', 'R', 'C', 'Lscr', 'Rscr', 'Ls', 'Rs', 'Lb', 'Rb', 'Tfl', 'Tfr', 'Tbl', 'Tbr'},
    15: {'L', 'R', 'C', 'LFE', 'LFE2', 'Lw', 'Rw', 'Ls', 'Rs', 'Lb', 'Rb', 'Bfl', 'Bfr', 'Bfc',
         'Cb', 'Tfl', 'Tfr', 'Tbl', 'Tbr', 'Tsl', 'Tsr', 'Tfc', 'Tbc', 'Tc'},
}
for _m in (4, 6, 8, 10, 12, 14):
    _CH_SETS[_m] = _CH_SETS[_m - 1] | {'LFE'}
_CORE_SETS = {3: {'L', 'R', 'C', 'Ls', 'Rs'}, 4: {'L', 'R', 'C', 'Ls', 'Rs', 'LFE'},
              5: {'L', 'R', 'C', 'Ls', 'Rs', 'Tl', 'Tr'},
              6: {'L', 'R', 'C', 'Ls', 'Rs', 'Tl', 'Tr', 'LFE'}}


def superset(a, b, sets=_CH_SETS):
    if a == -1:
        return b
    if b == -1:
        return a
    if {a, b} == {0, 1}:
        return 1
    need = sets[a] | sets[b]
    for m in sorted(sets):
        if need <= sets[m]:
            return m
    # Six pairs have no mode holding both - 5/2/0(.1) brings Lw/Rw and 9.X.4
    # brings Lscr/Rscr, 22.2 has the first pair and not the second - and
    # 6.3.3.1.27 gives no result for them. -1, the way the decoder reads it:
    # the presentation has no single channel mode, and the presentation
    # substream reads the fields that answer to that. Returning the larger mode
    # would name a layout the presentation does not have, dropping the LFE of
    # 5/2/0.1 against 9.0.4 (src/ac4dec/ERRATA.md, "The presentation
    # substream").
    return -1


