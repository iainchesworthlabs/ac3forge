def parse_presentation_substream(data, pc, flb, state, recs):
    """Part 2 6.2.2.3."""
    r = Reader(data, recs)
    if pc['b_alternative']:
        if r.f(1, 'b_name_present'):
            name_len = r.f(5, 'name_len') if r.f(1, 'b_length') else 32
            for _ in range(name_len):
                r.f(8, 'presentation_name')
        n_targets = r.f(2, 'n_targets_minus1') + 1
        if n_targets == 4:
            n_targets += r.vb(2, 'variable_bits')
        for _ in range(n_targets):
            r.f(3, 'target_level')
            r.f(4, 'target_device_category[]')
            if r.f(1, 'b_tdc_extension') == 1:
                r.f(4, 'reserved_bits')
            if r.f(1, 'b_ducking_depth_present'):
                r.f(6, 'max_ducking_depth')
            if r.f(1, 'b_loud_corr_target'):
                r.f(5, 'loud_corr_target')
            for _ in range(pc['n_substreams_in_presentation']):
                if r.f(1, 'b_active'):
                    if r.f(1, 'alt_data_set_index') == 1:
                        r.vb(2, 'variable_bits')
    if r.f(1, 'b_additional_data'):
        add_bytes = r.f(4, 'add_data_bytes_minus1') + 1
        if add_bytes == 16:
            add_bytes += r.vb(2, 'variable_bits')
        r.align()
        bits = add_bytes * 8
        r.f(1, 'immersive_audio_indicator')
        bits -= 1
        if pc['pres_ch_mode'] == -1:
            r.f(1, 'b_oamd_common_timing')
            bits -= 1
        b_advanced_de_data_present = r.f(1, 'b_advanced_de_data_present')
        bits -= 1
        if b_advanced_de_data_present:
            start = r.pos
            if r.f(1, 'b_advanced_de_config_present'):
                r.f(6, 'advanced_de_compr_tc_attack')
                r.f(6, 'advanced_de_compr_tc_release')
                r.f(4, 'advanced_de_compr_ratio')
            r.f(6, 'advanced_de_compr_thresh')
            r.f(5, 'advanced_de_compr_gain')
            bits -= r.pos - start
        if bits < 0:
            raise SyntaxFail(f'additional data overruns add_data_bytes by {-bits} bits')
        _wide(r, bits, 'add_data')
    r.f(7, 'dialnorm_bits')
    if r.f(1, 'b_further_loudness_info'):
        further_loudness_info(r, 1, 1)
    size = r.f(5, 'drc_metadata_size_value')
    if r.f(1, 'b_more_bits') == 1:
        size += r.vb(3, 'variable_bits') << 5
    start = r.pos
    drc_frame(r, pc['b_pres_ndot'], state, pc['pres_ch_mode'], flb)
    if r.pos - start != size:
        raise SyntaxFail(f'drc_frame used {r.pos - start} bits, drc_metadata_size says {size}')
    if pc['n_substream_groups'] > 1:
        if r.f(1, 'b_substream_group_gains_present') == 1:
            if r.f(1, 'b_keep') == 0:
                for _ in range(pc['n_substream_groups']):
                    r.f(6, 'sg_gain')
    if r.f(1, 'b_associated') == 1:
        if r.f(1, 'b_scale_main') == 1:
            r.f(8, 'scale_main')
        if r.f(1, 'b_scale_main_centre') == 1:
            r.f(8, 'scale_main_centre')
        if r.f(1, 'b_scale_main_front') == 1:
            r.f(8, 'scale_main_front')
        if r.f(1, 'b_associate_is_mono') == 1:
            r.f(8, 'pan_associated')
    custom_dmx_data(r, pc)
    loud_corr(r, pc['pres_ch_mode'], pc['pres_ch_mode_core'], 1 if pc['pres_ch_mode'] == -1 else 0)
    r.align()
    if r.pos != r.end:
        raise SyntaxFail(f'ac4_presentation_substream ends at byte {r.pos // 8}, '
                         f'substream_size is {r.end // 8}')


